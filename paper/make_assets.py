# ── helpers ───────────────────────────────────────────────────────────────────

def read_csv(path: str) -> list[dict]:
    with open(path, newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def key(dist: str, value: str | float) -> tuple[str, float]:
    v = float(value)
    return dist, int(v) if v.is_integer() and dist not in ("downscale", "faded_print", "white_balance") else v


def fmt_pct(x: float) -> str:
    return f"{x:.1f}"


def wilson(k: int, n: int, z: float = 1.959964) -> tuple[float, float]:
    if n == 0:
        return 0.0, 0.0
    p = k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return 100 * max(0.0, c - h), 100 * min(1.0, c + h)


class Macros:
    def __init__(self) -> None:
        self.lines: list[str] = ["% Generated by paper/make_assets.py; do not edit."]

    def add(self, name: str, value: object) -> None:
        assert name.isalpha(), name
        self.lines.append(f"\\newcommand{{\\{name}}}{{{value}}}")

    def write(self, path: str) -> None:
        with open(path, "w", encoding="utf-8") as f:
            f.write("\n".join(self.lines) + "\n")


def write(path: str, text: str) -> None:
    with open(path, "w", encoding="utf-8") as f:
        f.write("% Generated by paper/make_assets.py; do not edit.\n" + text)


