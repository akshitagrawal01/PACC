# ── N2 robustness ─────────────────────────────────────────────────────────────

def n2(run: str, res: dict, m: Macros) -> None:
    rows = read_csv(os.path.join(run, "n2_robustness.csv"))
    mc = {key(r["distortion"], r["value"]): r for r in read_csv(os.path.join(run, "n2_mcnemar_pacc2_vs_qrh.csv"))}
    table: dict[tuple, dict[str, dict]] = {}
    order: list[tuple] = []
    for r in rows:
        k = key(r["distortion"], r["value"])
        if k not in table:
            table[k] = {}
            order.append(k)
        table[k][r["codec"]] = r
    codecs = [c for c in CODECS if any(c in v for v in table.values())]
    trials = int(rows[0]["trials"])
    m.add("Trials", trials)
    m.add("NConditions", len(order))
    m.add("NFamilies", len({k[0] for k in order if k[0] != "everyday"}))
    m.add("NScenes", sum(1 for k in order if k[0] == "everyday"))
    m.add("NTrialsTotal", f"{trials * len(order):,}".replace(",", "{,}"))
    for c in codecs:
        m.add("Succ" + MACRO_CODEC[c], fmt_pct(res["N2"]["mean_success_pct"][c]))
        k_tot = sum(int(table[k][c]["successes"]) for k in order)
        n_tot = sum(int(table[k][c]["trials"]) for k in order)
        m.add("Fail" + MACRO_CODEC[c], n_tot - k_tot)
    m.add("McnSig", res["N2"]["significant_conditions_p_lt_0.05"])
    m.add("McnPaccBetter", res["N2"]["pacc_better_p_lt_0.05"])
    m.add("McnQrBetter", res["N2"]["qr_better_p_lt_0.05"])
    disc_n = sum(int(float(v["pacc2_only"] or 0)) for v in mc.values())
    disc_q = sum(int(float(v["qr_only"] or 0)) for v in mc.values())
    m.add("DiscPaccOnly", disc_n)
    m.add("DiscQrOnly", disc_q)
    worst_q = min(order, key=lambda k: float(table[k]["QR-H"]["rate_pct"]))
    m.add("QrHWorstRate", fmt_pct(float(table[worst_q]["QR-H"]["rate_pct"])))
    m.add("QrHWorstCond", CONDITION_LABEL.get(worst_q, str(worst_q)))

    head = " & ".join(CODEC_HEAD[c] for c in codecs)
    body = []
    for k in order:
        cells = []
        rates = [float(table[k][c]["rate_pct"]) for c in codecs]
        best = max(rates)
        for c, x in zip(codecs, rates):
            s = f"{x:.0f}" if x in (0.0, 100.0) else f"{x:.1f}"
            cells.append(f"\\textbf{{{s}}}" if x == best else s)
        mark = ""
        t = mc.get(k)
        if t is not None and float(t["p_value"]) < 0.05:
            mark = r"$^{\dagger}$"
        body.append(f"{CONDITION_LABEL.get(k, str(k))}{mark} & " + " & ".join(cells) + r" \\")
    means = [res["N2"]["mean_success_pct"][c] for c in codecs]
    best = max(means)
    mean_cells = [f"\\textbf{{{x:.1f}}}" if x == best else f"{x:.1f}" for x in means]
    write(os.path.join(GEN, "tab_n2.tex"),
          "\\begin{tabular}{@{}l" + "r" * len(codecs) + "@{}}\n\\toprule\n"
          f"Condition & {head} \\\\\n\\midrule\n" + "\n".join(body) +
          "\n\\midrule\n\\textit{Mean} & " + " & ".join(mean_cells) + " \\\\\n\\bottomrule\n\\end{tabular}\n")


# ── N1 density ────────────────────────────────────────────────────────────────

def n1(run: str, res: dict, m: Macros) -> None:
    rows = read_csv(os.path.join(run, "n1_equal_payload_side.csv"))
    ratios = []
    for r in rows:
        p = int(r["payload_bytes"])
        if 64 <= p <= 1024 and r["PACC-1-Q"] not in ("", "None") and r["QR-H"] not in ("", "None"):
            ratios.append((int(r["PACC-1-Q"]) / int(r["QR-H"])) ** 2)
    m.add("AreaRatioMin", f"{min(ratios):.2f}")
    m.add("AreaRatioMax", f"{max(ratios):.2f}")
    r16 = next(r for r in rows if int(r["payload_bytes"]) == 16)
    m.add("AreaRatioSixteen", f"{(int(r16['PACC-1-Q']) / int(r16['QR-H'])) ** 2:.2f}")
    m.add("SideSixteenPaccKQ", r16["PACC-1-Q"])
    m.add("SideSixteenQrM", r16["QR-M"])
    from pacc import codec as nc
    m.add("MaxCodeBits", f"{nc.code_params(148, 2, 3)[0]:,}".replace(",", "{,}"))
    r1k = next(r for r in rows if int(r["payload_bytes"]) == 1024)
    m.add("SideKiloPaccKQ", r1k["PACC-1-Q"])
    m.add("SideKiloPaccCQ", r1k["PACC-2-Q"])
    m.add("SideKiloQrH", r1k["QR-H"])
    m.add("SideKiloQrM", r1k["QR-M"])

    cap = read_csv(os.path.join(run, "n1_capacity.csv"))
    def bpm(codec, side):
        for r in cap:
            if r["codec"] == codec and int(r["side_modules"]) == side:
                return float(r["bits_per_module"])
        return None
    for c, name in (("PACC-1-Q", "BpmPaccKQ"), ("PACC-2-Q", "BpmPaccCQ"), ("PACC-1-L", "BpmPaccKL"), ("PACC-2-L", "BpmPaccCL")):
        v = bpm(c, 148)
        if v is not None:
            m.add(name, f"{v:.2f}")

    plt = mpl()
    fig, ax = plt.subplots(figsize=(3.45, 2.2))
    styles = {"PACC-1-Q": ("PACC, 4 colors, rate 1/2", "-", "o"), "PACC-2-Q": ("PACC, 8 colors, rate 1/2", "-", "s"),
              "PACC-1-H": ("PACC, 4 colors, rate 1/3", "-", "^"), "QR-M": ("QR level M", "--", "v"),
              "QR-H": ("QR level H", "--", "D")}
    xs = [int(r["payload_bytes"]) for r in rows]
    for c, (lab, ls, mk) in styles.items():
        pts = [(x, int(r[c])) for x, r in zip(xs, rows) if r[c] not in ("", "None")]
        ax.plot([p[0] for p in pts], [p[1] for p in pts], ls=ls, marker=mk, ms=3, label=lab,
                color="black" if c.startswith("QR") else None)
    ax.set_xscale("log", base=2)
    ax.set_xticks(xs)
    ax.set_xticklabels([str(x) for x in xs])
    ax.set_xlabel("Payload (bytes)")
    ax.set_ylabel("Symbol side (modules)")
    ax.grid(True, lw=0.3, alpha=0.5)
    ax.legend(frameon=False, loc="upper left")
    fig.savefig(os.path.join(FIG, "density.pdf"))
    plt.close(fig)


# ── N3 ablations ──────────────────────────────────────────────────────────────

def n3(run: str, res: dict, m: Macros) -> None:
    lim = res["N3"]["mean_success_pct"]
    eve = res["N3"]["everyday"]["mean_success_pct"]
    rows = read_csv(os.path.join(run, "n3_ablations.csv"))
    m.add("AblTrials", res["N3"]["trials"])
    m.add("AblNLimit", len(res["N3"]["conditions"]))
    m.add("AblNEveryday", len(res["N3"]["everyday"]["conditions"]))
    for c, cm in (("PACC-1-Q", "KQ"), ("PACC-2-Q", "CQ")):
        for a, _ in ABLATIONS:
            name = "Abl" + cm + "".join(p.capitalize() for p in a.replace("3pct", "Three").split("_"))
            m.add(name.replace("Three", "Three"), fmt_pct(lim[c][a]))
    ev_vals = {round(v, 1) for c in eve for v in eve[c].values()}
    m.add("AblEverydayMin", fmt_pct(min(ev_vals)))
    m.add("AblEverydayKQ", fmt_pct(eve["PACC-1-Q"]["full"]))

    per = {}
    for r in rows:
        if r["set"] != "limit":
            continue
        per.setdefault((r["codec"], r["ablation"]), {})[key(r["distortion"], r["value"])] = float(r["rate_pct"])
    conds = [key(*c.split("=")) for c in res["N3"]["conditions"]]
    head = " & ".join(f"\\rotatebox{{70}}{{{LIMIT_LABEL.get(c, str(c))}}}" for c in conds)
    body = []
    for a, lab in ABLATIONS:
        vals = [per.get(("PACC-1-Q", a), {}).get(c, float("nan")) for c in conds]
        body.append(f"{lab} & " + " & ".join(f"{v:.0f}" for v in vals) +
                    f" & \\textbf{{{lim['PACC-1-Q'][a]:.1f}}} & {lim['PACC-2-Q'][a]:.1f} \\\\")
    write(os.path.join(GEN, "tab_ablation.tex"),
          "\\begin{tabular}{@{}l" + "r" * len(conds) + "rr@{}}\n\\toprule\n"
          f" & {head} & \\shortstack{{Mean\\\\4c}} & \\shortstack{{Mean\\\\8c}} \\\\\n\\midrule\n" +
          "\n".join(body) + "\n\\bottomrule\n\\end{tabular}\n")


# ── N4 latency ────────────────────────────────────────────────────────────────

def n4(run: str, res: dict, m: Macros) -> None:
    rows = res["N4"]["rows"]
    sel = [r for r in rows if r["mcs"] == 1]
    r36 = next(r for r in sel if r["side_modules"] == 36)
    m.add("DecMsThirtySix", f"{r36['decode_ms_median']:.1f}")
    m.add("DecMsMax", f"{max(r['decode_ms_median'] for r in rows):.0f}")
    m.add("EncMsMax", f"{max(r['encode_ms_median'] for r in rows):.0f}")
    body = []
    for side in sorted({r["side_modules"] for r in rows}):
        cells = []
        for mcs in (0, 1, 2):
            r = next((x for x in rows if x["mcs"] == mcs and x["side_modules"] == side), None)
            cells += [str(r["payload_bytes"]), f"{r['decode_ms_median']:.1f}"] if r else ["--", "--"]
        body.append(f"{side} & " + " & ".join(cells) + r" \\")
    write(os.path.join(GEN, "tab_latency.tex"),
          "\\begin{tabular}{@{}rrrrrrr@{}}\n\\toprule\n"
          " & \\multicolumn{2}{c}{2 colors} & \\multicolumn{2}{c}{4 colors} & \\multicolumn{2}{c}{8 colors} \\\\\n"
          "\\cmidrule(lr){2-3}\\cmidrule(lr){4-5}\\cmidrule(lr){6-7}\n"
          "$N$ & bytes & ms & bytes & ms & bytes & ms \\\\\n\\midrule\n" + "\n".join(body) +
          "\n\\bottomrule\n\\end{tabular}\n")


# ── N6 multi-frame ────────────────────────────────────────────────────────────

def n6(run: str, res: dict, m: Macros) -> None:
    rows = res["N6"]["rows"]
    pacc = [r for r in rows if r["codec"] == "PACC-1-Q"]
    qr = [r for r in rows if r["codec"] == "QR-H"]
    m.add("MfTrials", rows[0]["trials"])
    m.add("MfPaccSingleMin", fmt_pct(min(r["single_frame_pct"] for r in pacc)))
    m.add("MfPaccSingleMax", fmt_pct(max(r["single_frame_pct"] for r in pacc)))
    m.add("MfQrSingleMin", fmt_pct(min(r["single_frame_pct"] for r in qr)))
    m.add("MfQrSingleMax", fmt_pct(max(r["single_frame_pct"] for r in qr)))
    m.add("MfQrEightMin", fmt_pct(min(r["any_frame_within_8_pct"] for r in qr)))
    m.add("MfQrEightMax", fmt_pct(max(r["any_frame_within_8_pct"] for r in qr)))
    lim = res["N6"]["limit"]["rows"]
    m.add("MfLimTrials", lim[0]["trials"])
    m.add("MfLimSingleMax", fmt_pct(max(r["single_frame_pct"] for r in lim)))
    four = [r["within_4_frames_pct"] for r in lim]
    m.add("MfLimFourMin", fmt_pct(min(four)))
    m.add("MfLimFourMax", fmt_pct(max(four)))

    plt = mpl()
    fig, axs = plt.subplots(1, 2, figsize=(7.1, 2.1), sharey=True)
    ks = list(range(1, res["N6"]["max_frames"] + 1))
    ax = axs[0]
    for r in rows:
        lab = ("PACC" if r["codec"].startswith("PACC") else "QR-H") + f", $\\sigma={r['noise_sigma']}$"
        ax.plot(ks, [r[f"any_frame_within_{k}_pct"] for k in ks], ls="--" if r["codec"] == "QR-H" else "-",
                marker="o", ms=2.5, label=lab)
    ax.set_title("(a) Everyday: first frame that decodes alone", fontsize=8)
    ax.set_xlabel("Frames observed")
    ax.set_ylabel("Decoded (%)")
    ax.legend(frameon=False, ncol=2, fontsize=6)
