# ── Equaliser illustration (grid-level channel, deterministic) ────────────────

def equaliser_figure(m: Macros) -> None:
    from pacc import codec, equalize, layout, modem
    rng = np.random.default_rng(20261124)
    enc = codec.encode_grid(bytes(rng.integers(0, 256, 300, dtype=np.uint8)), mcs=1, level="Q", compress=False)
    n = enc.n
    lay = layout.build(n)
    pal = np.asarray(codec.PALETTES[1]["rgb"], float) / 255.0
    clean = enc.grid.astype(float) / 255.0

    # Capture model at grid level: printer desaturation, warm cast, a soft shadow, sensor noise.
    rr, cc = np.mgrid[0:n, 0:n] / n
    shade = 1.0 - 0.55 * np.exp(-(((rr - 0.65) ** 2 + (cc - 0.35) ** 2) / 0.06))
    x = 0.22 + 0.62 * clean
    x = x * np.array([1.12, 0.98, 0.78])
    x = x * shade[..., None]
    x = np.clip(x + rng.normal(0, 0.035, x.shape), 0, 1)

    ref = np.zeros((n, n, 3))
    w = np.zeros((n, n))
    ref[lay.known_light] = 1.0
    w[lay.known_light | lay.known_dark] = 1.0
    for r, c in lay.pilot_cells:
        ref[r, c] = pal[layout.pilot_index(int(r), int(c), len(pal))]
        w[r, c] = 2.0
    from pacc import fmt
    info = fmt.FormatInfo(codec.grid_index(n), 1, 2)
    for corner in range(4):
        for (r, c), bit in zip(lay.format_cells[corner], fmt.corner_bits(corner, info)):
            ref[r, c] = 0.0 if bit else 1.0
            w[r, c] = 1.0

    dr, dc = lay.data_cells[:, 0], lay.data_cells[:, 1]
    truth = np.array([np.argmin(((pal - clean[r, c]) ** 2).sum(1)) for r, c in zip(dr, dc)])

    eq = equalize.fit(x, ref, w)
    y = eq.apply(x)
    cen, cov = equalize.constellation(y, ref, w, pal)

    def ser(points, centres, cv):
        ll = modem.symbol_loglik(points, centres, cv)
        return float(np.mean(ll.argmax(1) != truth))

    ser_raw = float(np.mean(((x[dr, dc][:, None, :] - pal[None]) ** 2).sum(-1).argmin(1) != truth))
    ser_nominal = ser(y[dr, dc], pal, eq.cov)
    ser_reest = ser(y[dr, dc], cen, cov)
    m.add("EqSerRaw", f"{100 * ser_raw:.1f}")
    m.add("EqSerNominal", f"{100 * ser_nominal:.1f}")
    m.add("EqSerReest", f"{100 * ser_reest:.1f}")
    m.add("EqN", n)

    def proj(v):
        v = np.asarray(v)
        return np.stack([(v[..., 0] - v[..., 1]) / np.sqrt(2), (v[..., 0] + v[..., 1] - 2 * v[..., 2]) / np.sqrt(6)], -1)

    plt = mpl()
    fig, axs = plt.subplots(1, 2, figsize=(3.45, 1.75), sharex=True, sharey=True)
    colours = ["#000000", "#00a6a6", "#c000c0", "#b0a000"]
    for ax, pts, title in ((axs[0], x[dr, dc], "(a) Captured"), (axs[1], y[dr, dc], "(b) Equalized")):
        p = proj(pts)
        for s in range(4):
            sel = truth == s
            ax.scatter(p[sel, 0], p[sel, 1], s=1.2, c=colours[s], alpha=0.35, lw=0)
        pn = proj(pal)
        ax.scatter(pn[:, 0], pn[:, 1], marker="x", s=22, c="red", lw=0.9, label="nominal palette")
        ax.set_title(title, fontsize=7)
        ax.grid(True, lw=0.3, alpha=0.5)
        ax.set_xlabel("$(R-G)/\\sqrt{2}$", fontsize=7)
    pc = proj(cen)
    axs[1].scatter(pc[:, 0], pc[:, 1], marker="+", s=34, c="blue", lw=0.9, label="re-estimated center")
    axs[0].set_ylabel("$(R+G-2B)/\\sqrt{6}$", fontsize=7)
    axs[1].legend(loc="upper left", frameon=True, framealpha=0.9, edgecolor="none", fontsize=5.5,
                  handletextpad=0.3, borderpad=0.3, labelspacing=0.3)
    fig.savefig(os.path.join(FIG, "equaliser.pdf"), dpi=600)
    plt.close(fig)


